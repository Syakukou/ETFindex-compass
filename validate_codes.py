def main():
    df = ak.fund_etf_spot_em()
    known = {}
    for _, r in df.iterrows():
        known[str(r["代码"])] = str(r["名称"])
    ok, bad = [], []
    for code, cat in CANDIDATES:
        if code in known:
            ok.append({"code": code, "name": known[code], "category": cat})
        else:
            bad.append((code, cat))
    print(f"验证通过 {len(ok)} 只, 失败 {len(bad)} 只")
    for c, cat in bad:
        print(f"  无效代码: {c} ({cat})")
    with open("etf_candidates_validated.json", "w", encoding="utf-8") as f:
        json.dump(ok, f, ensure_ascii=False, indent=2)
    print("已写入 etf_candidates_validated.json")

if __name__ == "__main__":
    main()
